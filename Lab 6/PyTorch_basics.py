import torch

# Create tensors
a = torch.tensor([10, 20, 30])
b = torch.tensor([1, 2, 3])

# Display tensors
print("Tensor A:", a)
print("Tensor B:", b)

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Find sum
print("Sum of A:", torch.sum(a))

# Find mean
print("Mean of A:", torch.mean(a.float()))

